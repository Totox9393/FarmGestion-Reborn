create or replace function public.redeem_surprise_code_reborn(
  p_code text,
  p_device_id text default null,
  p_source text default null
)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_code public.surprise_codes_reborn%rowtype;
  v_profile public.users_profiles%rowtype;
  v_now timestamptz := now();
  v_clean_code text := upper(trim(coalesce(p_code, '')));
  v_clean_device_id text := nullif(trim(coalesce(p_device_id, '')), '');
  v_headers_text text := current_setting('request.headers', true);
  v_headers jsonb := '{}'::jsonb;
  v_ip_raw text := null;
  v_ip inet := null;
  v_total_uses integer := 0;
  v_awarded_money integer := 0;
  v_awarded_badge uuid := null;
  v_awarded_badges uuid[] := '{}';
  v_code_badges uuid[] := '{}';
  v_candidate_badge uuid;
begin
  if v_user_id is null then
    return json_build_object('success', false, 'reason', 'NOT_AUTHENTICATED');
  end if;

  if v_clean_code = '' then
    return json_build_object('success', false, 'reason', 'EMPTY_CODE');
  end if;

  select *
  into v_code
  from public.surprise_codes_reborn
  where upper(trim(code)) = v_clean_code
    and is_enabled = true
  for update;

  if not found then
    return json_build_object('success', false, 'reason', 'CODE_NOT_FOUND');
  end if;

  if v_code.valid_from > v_now then
    return json_build_object('success', false, 'reason', 'CODE_NOT_STARTED');
  end if;

  if v_code.valid_until is not null and v_code.valid_until < v_now then
    return json_build_object('success', false, 'reason', 'CODE_EXPIRED');
  end if;

  select *
  into v_profile
  from public.users_profiles
  where id = v_user_id
  for update;

  if not found then
    return json_build_object('success', false, 'reason', 'PROFILE_NOT_FOUND');
  end if;

  if v_code.limit_per_account and exists (
    select 1
    from public.surprise_code_redemptions_reborn r
    where r.code_id = v_code.id
      and r.user_id = v_user_id
  ) then
    return json_build_object('success', false, 'reason', 'ALREADY_REDEEMED_ACCOUNT');
  end if;

  if v_code.limit_per_device and v_clean_device_id is not null and exists (
    select 1
    from public.surprise_code_redemptions_reborn r
    where r.code_id = v_code.id
      and r.device_id = v_clean_device_id
  ) then
    return json_build_object('success', false, 'reason', 'ALREADY_REDEEMED_DEVICE');
  end if;

  if v_headers_text is not null and trim(v_headers_text) <> '' then
    begin
      v_headers := v_headers_text::jsonb;
    exception when others then
      v_headers := '{}'::jsonb;
    end;
  end if;

  v_ip_raw := split_part(coalesce(v_headers ->> 'x-forwarded-for', ''), ',', 1);
  if v_ip_raw = '' then
    v_ip_raw := v_headers ->> 'x-real-ip';
  end if;

  begin
    if v_ip_raw is not null and trim(v_ip_raw) <> '' then
      v_ip := trim(v_ip_raw)::inet;
    end if;
  exception when others then
    v_ip := null;
  end;

  if v_code.limit_per_ip and v_ip is not null and exists (
    select 1
    from public.surprise_code_redemptions_reborn r
    where r.code_id = v_code.id
      and r.ip_address = v_ip
  ) then
    return json_build_object('success', false, 'reason', 'ALREADY_REDEEMED_IP');
  end if;

  select count(*)::integer
  into v_total_uses
  from public.surprise_code_redemptions_reborn r
  where r.code_id = v_code.id;

  if v_code.single_global_use and v_total_uses >= 1 then
    return json_build_object('success', false, 'reason', 'CODE_ALREADY_USED');
  end if;

  if v_code.max_total_uses is not null and v_total_uses >= v_code.max_total_uses then
    return json_build_object('success', false, 'reason', 'CODE_EXHAUSTED');
  end if;

  if v_code.bonus_money > 0 then
    v_awarded_money := v_code.bonus_money;
    update public.users_profiles
    set money = coalesce(money, 0) + v_awarded_money,
        updated_at = now()
    where id = v_user_id;
  end if;

  v_code_badges := array_remove(coalesce(v_code.bonus_badge_ids, '{}'), null);
  if v_code.bonus_badge_id is not null and not (v_code.bonus_badge_id = any(v_code_badges)) then
    v_code_badges := array_append(v_code_badges, v_code.bonus_badge_id);
  end if;

  foreach v_candidate_badge in array v_code_badges loop
    if not exists (
      select 1
      from public.badges_inventory_reborn inv
      where inv.user_id = v_user_id
        and inv.badge_id = v_candidate_badge
    ) then
      insert into public.badges_inventory_reborn (
        user_id,
        badge_id,
        purchase_price,
        purchased_at
      ) values (
        v_user_id,
        v_candidate_badge,
        0,
        now()
      );

      v_awarded_badges := array_append(v_awarded_badges, v_candidate_badge);
      if v_awarded_badge is null then
        v_awarded_badge := v_candidate_badge;
      end if;
    end if;
  end loop;

  insert into public.surprise_code_redemptions_reborn (
    code_id,
    code_snapshot,
    user_id,
    device_id,
    ip_address,
    source,
    awarded_money,
    awarded_badge_id,
    awarded_badge_ids
  ) values (
    v_code.id,
    v_code.code,
    v_user_id,
    v_clean_device_id,
    v_ip,
    nullif(trim(coalesce(p_source, '')), ''),
    v_awarded_money,
    v_awarded_badge,
    v_awarded_badges
  );

  update public.surprise_codes_reborn
  set updated_at = now()
  where id = v_code.id;

  return json_build_object(
    'success', true,
    'code', v_code.code,
    'awarded_money', v_awarded_money,
    'awarded_badge_id', v_awarded_badge,
    'awarded_badge_ids', v_awarded_badges,
    'reason', 'REDEEMED'
  );
end;
$$;

grant execute on function public.redeem_surprise_code_reborn(text, text, text) to authenticated;
