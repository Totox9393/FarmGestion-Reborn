alter table if exists public.badges_catalog_reborn
  add column if not exists is_shop_visible boolean not null default true;

create table if not exists public.surprise_codes_reborn (
  id uuid primary key default gen_random_uuid(),
  code text not null,
  label text,
  description text,
  bonus_money integer not null default 0,
  bonus_badge_id uuid references public.badges_catalog_reborn(id) on delete set null,
  bonus_badge_ids uuid[] not null default '{}',
  valid_from timestamptz not null default now(),
  valid_until timestamptz,
  is_enabled boolean not null default true,
  single_global_use boolean not null default false,
  max_total_uses integer,
  limit_per_account boolean not null default true,
  limit_per_device boolean not null default true,
  limit_per_ip boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint surprise_codes_reborn_code_not_blank check (length(trim(code)) >= 3),
  constraint surprise_codes_reborn_bonus_not_empty check (
    bonus_money > 0
    or bonus_badge_id is not null
    or coalesce(array_length(bonus_badge_ids, 1), 0) > 0
  ),
  constraint surprise_codes_reborn_dates_valid check (valid_until is null or valid_until >= valid_from),
  constraint surprise_codes_reborn_max_uses_valid check (max_total_uses is null or max_total_uses > 0),
  constraint surprise_codes_reborn_single_global_rule check (
    not single_global_use or max_total_uses is null or max_total_uses = 1
  )
);

create unique index if not exists surprise_codes_reborn_code_ci_uidx
  on public.surprise_codes_reborn (upper(trim(code)));

create table if not exists public.surprise_code_redemptions_reborn (
  id bigint generated by default as identity primary key,
  code_id uuid not null references public.surprise_codes_reborn(id) on delete cascade,
  code_snapshot text not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  device_id text,
  ip_address inet,
  source text,
  awarded_money integer not null default 0,
  awarded_badge_id uuid references public.badges_catalog_reborn(id) on delete set null,
  awarded_badge_ids uuid[] not null default '{}',
  created_at timestamptz not null default now(),
  constraint surprise_code_redemptions_reborn_awarded_valid check (awarded_money >= 0)
);

alter table if exists public.surprise_codes_reborn
  add column if not exists bonus_badge_ids uuid[] not null default '{}';

alter table if exists public.surprise_codes_reborn
  add column if not exists description text;

alter table if exists public.surprise_code_redemptions_reborn
  add column if not exists awarded_badge_ids uuid[] not null default '{}';

create unique index if not exists surprise_code_redemptions_reborn_user_uidx
  on public.surprise_code_redemptions_reborn (code_id, user_id);

create index if not exists surprise_code_redemptions_reborn_code_idx
  on public.surprise_code_redemptions_reborn (code_id, created_at desc);

create index if not exists surprise_code_redemptions_reborn_device_idx
  on public.surprise_code_redemptions_reborn (code_id, device_id)
  where device_id is not null;

create index if not exists surprise_code_redemptions_reborn_ip_idx
  on public.surprise_code_redemptions_reborn (code_id, ip_address)
  where ip_address is not null;

alter table public.surprise_codes_reborn enable row level security;
alter table public.surprise_code_redemptions_reborn enable row level security;

